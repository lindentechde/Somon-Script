import { compile } from '../src/compiler';
import * as vm from 'vm';

/**
 * Every TypeScript operator and statement (llm-guide/14-operators.md) in
 * SomonScript: each program must compile with and without strict mode and
 * print the expected output.
 */

/** Lets asynchronous programs (`интизор`, `барои интизор`) finish printing. */
async function settle(): Promise<void> {
  for (let i = 0; i < 10; i++) {
    await new Promise(resolve => setImmediate(resolve));
  }
}

async function expectOutput(source: string, expected: string): Promise<void> {
  for (const strict of [false, true]) {
    const result = compile(source, { strict });
    expect(result.errors).toEqual([]);
    const lines: string[] = [];
    const log = (...args: unknown[]): void => {
      lines.push(args.map(String).join(' '));
    };
    vm.runInNewContext(result.code, { console: { log } });
    await settle();
    expect(lines.join('\n')).toBe(expected);
  }
}

